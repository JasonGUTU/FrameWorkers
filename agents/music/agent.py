"""MusicAgent — single film-global background music cue.

Post-refactor shape: the agent emits **one** MusicCue whose duration covers
the whole film. Per-scene cues / scene_id are gone — scene-level alignment
is no longer meaningful in the new audio architecture (Kling bakes
dialogue + foley into each video clip, leaving BGM as a pure global
underlay laid on top by the downstream audio-mix step).
"""

from __future__ import annotations

from typing import Any

from ..base_agent import BaseAgent
from .schema import MusicAgentInput, MusicAgentOutput


MUSIC_OUTPUT_TEMPLATE = """{
  "content": {
    "cues": [
      {
        "cue_id": "music_film",
        "mood": "<3-6 keywords: musical mood + instrumentation spanning the WHOLE film>",
        "duration_seconds": 45.0
      }
    ]
  }
}"""


class MusicAgent(BaseAgent[MusicAgentInput, MusicAgentOutput]):

    async def generate(self, input_data: MusicAgentInput, *, rework_notes: str = "") -> MusicAgentOutput:
        output = await self._llm_fill_full(input_data, rework_notes)
        self.recompute_metrics(output)
        return output

    def system_prompt(self) -> str:
        return (
            "You are MusicAgent: read a screenplay OR a video-analysis "
            "artifact and produce ONE background music cue that spans the "
            "ENTIRE film.\n\n"
            "=== WHEN TO REJECT UPSTREAM INPUT ===\n"
            "Use the shared input_rejection escape hatch (see the UPSTREAM "
            "INPUT REJECTION block above) ONLY if BOTH sources are unusable. "
            "Concretely, reject when ALL of these are true:\n"
            "  * screenplay_json_text is empty / whitespace-only / empty "
            "JSON object, OR has no scenes anywhere (content.scenes empty "
            "or missing).\n"
            "  * video_analysis_json_text is ALSO empty / whitespace-only / "
            "empty JSON object, OR has no scenes (content.scenes empty).\n"
            "If EITHER source has usable content — DO NOT reject; use the "
            "one that is populated.\n"
            "When you reject, populate the rejection fields like this:\n"
            "  * reason: the single most specific defect (e.g. 'both "
            "screenplay and video_analysis are empty').\n"
            "  * missing_labels: ['screenplay', 'video_analysis'].\n"
            "  * offending_fields: e.g. ['content.scenes'].\n"
            "Thin tone / mood descriptions are NOT a reject reason — "
            "infer mood from whatever descriptive text is present.\n"
            "=== END WHEN TO REJECT UPSTREAM INPUT ===\n\n"
            "=== OUTPUT SHAPE ===\n"
            "Emit EXACTLY ONE cue in `content.cues` covering the full "
            "film. There is no scene_id; the cue is film-wide.\n"
            "  cue_id: always 'music_film'.\n"
            "The wav file for this cue is generated by the materializer "
            "and registered as a separate artifact (sys_id "
            "'aud_music_film') in workspace memory; do NOT include any "
            "audio asset / uri / file-path field in your JSON output.\n\n"
            "=== MOOD ===\n"
            "Derive a single cohesive mood + instrumentation string that "
            "fits the film's overall tone (e.g. 'melancholic, ambient, "
            "solo piano, sparse strings'). Prefer 3-6 keywords. Choose a "
            "bed that works under dialogue and action alike — BGM is an "
            "underlay, not a scene score.\n"
            "  * With a screenplay: infer mood from genre / tone_keywords "
            "and per-shot descriptive text.\n"
            "  * With only a video_analysis: aggregate "
            "content.scenes[*].mood across scenes and lean on "
            "content.video_summary.genre.\n\n"
            "=== DURATION ===\n"
            "Compute duration_seconds as a decimal number of seconds:\n"
            "  * With a screenplay — use this exact formula summed across "
            "EVERY shot in EVERY scene:\n"
            "      dialogue_words = total word count across all shots "
            "whose block_type is 'dialogue', 'narration', or 'monologue' "
            "(count words in shot.text, whitespace-split).\n"
            "      action_shots = count of shots whose block_type == "
            "'action'.\n"
            "      duration_seconds = (dialogue_words / 2.5) + "
            "(action_shots * 3.0).\n"
            "    (2.5 words/sec ≈ 150 wpm TTS rate; 3s-per-action-shot "
            "reserves visual-pacing time.)\n"
            "  * With only a video_analysis — use "
            "content.video_summary.duration_seconds directly as the "
            "target; if it is 0 / missing, sum scenes[*].end_time of the "
            "last scene.\n"
            "  * Round to one decimal place. Must be strictly > 0.\n"
            "  * The downstream audio-mix step will amix this cue against "
            "the actual video duration and trim — this number is a "
            "sensible target, not a hard contract.\n\n"
            "JSON only; no markdown.\n"
            "Do NOT include an artifact_caption block."
        )

    def build_user_prompt(self, input_data: MusicAgentInput) -> str:
        parts = ["Produce a single film-wide music cue for this source.\n\n"]
        if input_data.screenplay_json_text:
            parts.append(
                "=== SCREENPLAY ===\n"
                f"{input_data.screenplay_json_text}\n"
                "=== END SCREENPLAY ===\n\n"
            )
        if input_data.video_analysis_json_text:
            parts.append(
                "=== VIDEO ANALYSIS ===\n"
                f"{input_data.video_analysis_json_text}\n"
                "=== END VIDEO ANALYSIS ===\n\n"
            )
        parts.append(f"Output:\n{MUSIC_OUTPUT_TEMPLATE}\n\nReturn JSON only.")
        return "".join(parts)

    def parse_output(self, raw: dict[str, Any]) -> MusicAgentOutput:
        return MusicAgentOutput.model_validate(raw)

    def recompute_metrics(self, output: MusicAgentOutput) -> None:
        output.metrics.cue_count = len(output.content.cues)
