"""MusicAgent — single film-global background music cue.

Post-refactor shape: the agent emits **one** MusicCue whose mood covers
the whole film. Per-scene cues / scene_id are gone — scene-level alignment
is no longer meaningful in the new audio architecture (the video-generation
backend bakes dialogue + foley into each video clip, leaving BGM as a pure
global underlay laid on top by the downstream audio-mix step).
"""

from __future__ import annotations

from typing import Any

from ..base_agent import BaseAgent
from .schema import MusicAgentInput, MusicAgentOutput


MUSIC_OUTPUT_TEMPLATE = """{
  "content": {
    "cues": [
      {
        "cue_id": "music_film",
        "mood": "<3-6 keywords: musical mood + instrumentation spanning the WHOLE film>"
      }
    ]
  }
}"""


class MusicAgent(BaseAgent[MusicAgentInput, MusicAgentOutput]):

    async def generate(self, input_data: MusicAgentInput, *, rework_notes: str = "") -> MusicAgentOutput:
        output = await self._llm_fill_full(input_data, rework_notes)
        self.recompute_metrics(output)
        return output

    def system_prompt(self) -> str:
        return (
            "You are MusicAgent: produce ONE film-wide background music "
            "cue. Your only job is picking the cue's mood from any "
            "available upstream content signal.\n\n"
            "=== WHEN TO REJECT UPSTREAM INPUT ===\n"
            "Use the shared input_rejection escape hatch ONLY when NONE "
            "of the upstream content sources carry any cue you can use "
            "to pick a mood. Reject only when ALL of these are true:\n"
            "  * screenplay_json_text is empty / whitespace-only / empty "
            "JSON.\n"
            "  * video_analysis_json_text is empty / whitespace-only / "
            "empty JSON.\n"
            "  * creative_brief_json_text is empty / whitespace-only / "
            "empty JSON, OR carries no descriptive content at all (just "
            "a format request like 'output mp4' with no subject / "
            "setting / mood / instrumentation cue anywhere).\n"
            "If ANY of the three carries usable descriptive content — "
            "DO NOT reject. Mood signal can come from named instruments "
            "in the brief ('piano background score'), genre cues ('rainy "
            "night scene'), narration content (lullaby story → gentle), "
            "scene moods, or screenplay tone_keywords. Sparse hints are "
            "enough; expanding them is your job.\n"
            "When you reject, populate:\n"
            "  * reason: the single most specific defect.\n"
            "  * missing_labels: ['screenplay', 'video_analysis', "
            "'creative_brief'].\n"
            "  * offending_fields: e.g. ['content.text'].\n"
            "=== END WHEN TO REJECT UPSTREAM INPUT ===\n\n"
            "=== OUTPUT SHAPE ===\n"
            "Emit EXACTLY ONE cue in `content.cues` covering the full "
            "film. cue_id: always 'music_film'.\n"
            "The wav file for this cue is generated by the materializer "
            "and registered as a separate artifact (sys_id "
            "'aud_music_film') in workspace memory; do NOT include any "
            "audio asset / uri / file-path field in your JSON output. "
            "Track length is not a creative decision — the downstream "
            "audio-mix step's ffmpeg amix duration=first filter "
            "trims/loops against the actual video, so do NOT emit a "
            "duration field.\n\n"
            "=== MOOD ===\n"
            "Derive a single cohesive mood + instrumentation string that "
            "fits the film's overall tone (e.g. 'melancholic, ambient, "
            "solo piano, sparse strings'). Prefer 3-6 keywords. Choose a "
            "bed that works under dialogue and action alike — BGM is an "
            "underlay, not a scene score. Read whichever upstream blocks "
            "are populated; the brief is often the most direct signal "
            "of what the user wants ('with a gentle, slow piano score' "
            "→ 'gentle, slow, solo piano, soft, intimate').\n\n"
            "JSON only; no markdown.\n"
            "Do NOT include an artifact_caption block."
        )

    def build_user_prompt(self, input_data: MusicAgentInput) -> str:
        parts = ["Produce a single film-wide music cue for this source.\n\n"]
        if input_data.screenplay_json_text:
            parts.append(
                "=== SCREENPLAY ===\n"
                f"{input_data.screenplay_json_text}\n"
                "=== END SCREENPLAY ===\n\n"
            )
        if input_data.video_analysis_json_text:
            parts.append(
                "=== VIDEO ANALYSIS ===\n"
                f"{input_data.video_analysis_json_text}\n"
                "=== END VIDEO ANALYSIS ===\n\n"
            )
        if input_data.creative_brief_json_text:
            parts.append(
                "=== CREATIVE BRIEF (raw JSON — read the user's verbatim "
                "request from it) ===\n"
                f"{input_data.creative_brief_json_text}\n"
                "=== END CREATIVE BRIEF ===\n\n"
            )
        parts.append(f"Output:\n{MUSIC_OUTPUT_TEMPLATE}\n\nReturn JSON only.")
        return "".join(parts)

    def parse_output(self, raw: dict[str, Any]) -> MusicAgentOutput:
        return MusicAgentOutput.model_validate(raw)

    def recompute_metrics(self, output: MusicAgentOutput) -> None:
        output.metrics.cue_count = len(output.content.cues)
