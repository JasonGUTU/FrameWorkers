"""AmbienceAgent — single film-global ambience bed.

Post-refactor shape: the agent emits **one** AmbienceBed whose description
covers the whole film. Per-scene beds / scene_id are gone — the video-
generation backend bakes scene-synchronized foley (footsteps, impacts,
object sounds) into each video clip; this bed is the continuous room-tone
underlay that fills between foley events and is mixed in by the downstream
audio-mix step globally.
"""

from __future__ import annotations

from typing import Any

from ..base_agent import BaseAgent
from .schema import AmbienceAgentInput, AmbienceAgentOutput


AMBIENCE_OUTPUT_TEMPLATE = """{
  "content": {
    "beds": [
      {
        "ambience_id": "amb_film",
        "description": "<short description of the film-wide ambient underlay>"
      }
    ]
  }
}"""


class AmbienceAgent(BaseAgent[AmbienceAgentInput, AmbienceAgentOutput]):

    async def generate(self, input_data: AmbienceAgentInput, *, rework_notes: str = "") -> AmbienceAgentOutput:
        output = await self._llm_fill_full(input_data, rework_notes)
        self.recompute_metrics(output)
        return output

    def system_prompt(self) -> str:
        return (
            "You are AmbienceAgent: produce ONE film-wide ambient sound "
            "bed (room tone / environmental underlay). Your only job is "
            "picking the bed's description from any available upstream "
            "content signal.\n\n"
            "=== WHEN TO REJECT UPSTREAM INPUT ===\n"
            "Use the shared input_rejection escape hatch ONLY when NONE "
            "of the upstream content sources carry any cue you can use "
            "to pick an ambient texture. Reject only when ALL of these "
            "are true:\n"
            "  * screenplay_json_text is empty / whitespace-only / "
            "empty JSON.\n"
            "  * video_analysis_json_text is empty / whitespace-only / "
            "empty JSON.\n"
            "  * creative_brief_json_text is empty / whitespace-only / "
            "empty JSON, OR carries no environment / atmosphere cue "
            "anywhere (no setting, location, weather, vibe).\n"
            "If ANY of the three carries usable descriptive content — "
            "DO NOT reject. Environment cues can come from named "
            "settings in the brief ('rainy night street'), narration "
            "content (forest scene → wind / leaves), scene settings, "
            "or screenplay locations. Sparse hints are enough; if "
            "nothing specific is given, default to a generic 'soft "
            "room tone'.\n"
            "When you reject, populate:\n"
            "  * reason: the single most specific defect.\n"
            "  * missing_labels: ['screenplay', 'video_analysis', "
            "'creative_brief'].\n"
            "  * offending_fields: e.g. ['content.text'].\n"
            "=== END WHEN TO REJECT UPSTREAM INPUT ===\n\n"
            "=== OUTPUT SHAPE ===\n"
            "Emit EXACTLY ONE bed in `content.beds` covering the full "
            "film. ambience_id: always 'amb_film'.\n"
            "The wav file for this bed is generated by the materializer "
            "and registered as a separate artifact (sys_id "
            "'aud_amb_film') in workspace memory; do NOT include any "
            "audio asset / uri / file-path field in your JSON output. "
            "Track length is not a creative decision — the downstream "
            "audio-mix step's ffmpeg amix duration=first filter "
            "trims/loops against the actual video, so do NOT emit a "
            "duration field.\n\n"
            "=== DESCRIPTION ===\n"
            "Derive a single continuous ambient texture that suits the "
            "film's dominant environment(s). Read whichever upstream "
            "blocks are populated; the brief is often the most direct "
            "signal ('rainy-night scene' → 'gentle rain on pavement, "
            "distant traffic, soft urban hum'). If the film is mostly "
            "one setting (forest, coffee shop, spaceship cabin), pick "
            "that room tone. If scenes span multiple locations, pick a "
            "neutral underlay (soft wind, gentle room tone, subdued "
            "hum). Scene-specific foley is already baked into each "
            "video clip, so this bed just fills gaps.\n\n"
            "JSON only; no markdown.\n"
            "Do NOT include an artifact_caption block."
        )

    def build_user_prompt(self, input_data: AmbienceAgentInput) -> str:
        parts = ["Produce a single film-wide ambience bed for this source.\n\n"]
        if input_data.screenplay_json_text:
            parts.append(
                "=== SCREENPLAY ===\n"
                f"{input_data.screenplay_json_text}\n"
                "=== END SCREENPLAY ===\n\n"
            )
        if input_data.video_analysis_json_text:
            parts.append(
                "=== VIDEO ANALYSIS ===\n"
                f"{input_data.video_analysis_json_text}\n"
                "=== END VIDEO ANALYSIS ===\n\n"
            )
        if input_data.creative_brief_json_text:
            parts.append(
                "=== CREATIVE BRIEF (raw JSON — read the user's verbatim "
                "request from it) ===\n"
                f"{input_data.creative_brief_json_text}\n"
                "=== END CREATIVE BRIEF ===\n\n"
            )
        parts.append(f"Output:\n{AMBIENCE_OUTPUT_TEMPLATE}\n\nReturn JSON only.")
        return "".join(parts)

    def parse_output(self, raw: dict[str, Any]) -> AmbienceAgentOutput:
        return AmbienceAgentOutput.model_validate(raw)

    def recompute_metrics(self, output: AmbienceAgentOutput) -> None:
        output.metrics.bed_count = len(output.content.beds)
