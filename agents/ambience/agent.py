"""AmbienceAgent — single film-global ambience bed.

Post-refactor shape: the agent emits **one** AmbienceBed whose duration
covers the whole film. Per-scene beds / scene_id are gone — Kling bakes
scene-synchronized foley (footsteps, impacts, object sounds) into each
video clip; this bed is the continuous room-tone underlay that fills
between foley events and is mixed in by the downstream audio-mix step globally.
"""

from __future__ import annotations

from typing import Any

from ..base_agent import BaseAgent
from .schema import AmbienceAgentInput, AmbienceAgentOutput


AMBIENCE_OUTPUT_TEMPLATE = """{
  "content": {
    "beds": [
      {
        "ambience_id": "amb_film",
        "description": "<short description of the film-wide ambient underlay>",
        "duration_seconds": 45.0
      }
    ]
  }
}"""


class AmbienceAgent(BaseAgent[AmbienceAgentInput, AmbienceAgentOutput]):

    async def generate(self, input_data: AmbienceAgentInput, *, rework_notes: str = "") -> AmbienceAgentOutput:
        output = await self._llm_fill_full(input_data, rework_notes)
        self.recompute_metrics(output)
        return output

    def system_prompt(self) -> str:
        return (
            "You are AmbienceAgent: read a screenplay OR a video-analysis "
            "artifact and produce ONE ambient sound bed that spans the "
            "ENTIRE film.\n\n"
            "=== WHEN TO REJECT UPSTREAM INPUT ===\n"
            "Use the shared input_rejection escape hatch (see the UPSTREAM "
            "INPUT REJECTION block above) ONLY if BOTH sources are unusable. "
            "Concretely, reject when ALL of these are true:\n"
            "  * screenplay_json_text is empty / whitespace-only / empty "
            "JSON object, OR has no scenes (content.scenes empty or "
            "missing).\n"
            "  * video_analysis_json_text is ALSO empty / whitespace-only "
            "/ empty JSON object, OR has no scenes.\n"
            "If EITHER source has usable content — DO NOT reject.\n"
            "When you reject:\n"
            "  * reason: the single most specific defect (e.g. 'both "
            "screenplay and video_analysis are empty').\n"
            "  * missing_labels: ['screenplay', 'video_analysis'].\n"
            "  * offending_fields: e.g. ['content.scenes'].\n"
            "Thin location / environment descriptions are NOT a reject "
            "reason — use a generic 'room tone' when nothing is specified.\n"
            "=== END WHEN TO REJECT UPSTREAM INPUT ===\n\n"
            "=== OUTPUT SHAPE ===\n"
            "Emit EXACTLY ONE bed in `content.beds` covering the full "
            "film. There is no scene_id; the bed is film-wide.\n"
            "  ambience_id: always 'amb_film'.\n"
            "The wav file for this bed is generated by the materializer "
            "and registered as a separate artifact (sys_id "
            "'aud_amb_film') in workspace memory; do NOT include any "
            "audio asset / uri / file-path field in your JSON output.\n\n"
            "=== DESCRIPTION ===\n"
            "Derive a single continuous ambient texture that suits the "
            "film's dominant environment(s).\n"
            "  * With a screenplay: read the dominant location(s) from "
            "scenes[*] and pick a matching room tone.\n"
            "  * With only a video_analysis: aggregate "
            "content.scenes[*].setting to identify the dominant "
            "environment.\n"
            "If the film is mostly one setting (e.g. a forest, a coffee "
            "shop, a spaceship cabin), pick that room tone. If scenes "
            "span multiple locations, pick a neutral underlay (soft "
            "wind, gentle room tone, subdued hum). Scene-specific foley "
            "is already baked into each video clip, so this bed just "
            "fills gaps.\n\n"
            "=== DURATION ===\n"
            "Compute duration_seconds so Music and Ambience stay "
            "naturally aligned:\n"
            "  * With a screenplay — use the same dialogue_words / action_shots "
            "formula as the music step:\n"
            "      dialogue_words = total word count across all shots "
            "whose block_type is 'dialogue', 'narration', or 'monologue' "
            "in the entire screenplay.\n"
            "      action_shots = count of shots whose block_type == "
            "'action'.\n"
            "      duration_seconds = (dialogue_words / 2.5) + "
            "(action_shots * 3.0).\n"
            "  * With only a video_analysis — use "
            "content.video_summary.duration_seconds directly; if 0 / "
            "missing, take scenes[-1].end_time.\n"
            "  * Round to one decimal place. Must be strictly > 0.\n"
            "  * The downstream audio-mix step amix+trims against "
            "the actual video.\n\n"
            "JSON only; no markdown.\n"
            "Do NOT include an artifact_caption block."
        )

    def build_user_prompt(self, input_data: AmbienceAgentInput) -> str:
        parts = ["Produce a single film-wide ambience bed for this source.\n\n"]
        if input_data.screenplay_json_text:
            parts.append(
                "=== SCREENPLAY ===\n"
                f"{input_data.screenplay_json_text}\n"
                "=== END SCREENPLAY ===\n\n"
            )
        if input_data.video_analysis_json_text:
            parts.append(
                "=== VIDEO ANALYSIS ===\n"
                f"{input_data.video_analysis_json_text}\n"
                "=== END VIDEO ANALYSIS ===\n\n"
            )
        parts.append(f"Output:\n{AMBIENCE_OUTPUT_TEMPLATE}\n\nReturn JSON only.")
        return "".join(parts)

    def parse_output(self, raw: dict[str, Any]) -> AmbienceAgentOutput:
        return AmbienceAgentOutput.model_validate(raw)

    def recompute_metrics(self, output: AmbienceAgentOutput) -> None:
        output.metrics.bed_count = len(output.content.beds)
